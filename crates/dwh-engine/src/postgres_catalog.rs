/// Column and privilege metadata for an explicit relation list. Does not read row bodies.
pub fn scan_postgres_import(
    db: &DbSession,
    connection_string: &str,
    relations: &[(String, String)],
) -> Result<Vec<PgRelationSnapshot>, String> {
    let rel_sql = relations_catalog_sql(relations)?;
    let col_sql = columns_catalog_sql(relations)?;
    let con_sql = constraints_catalog_sql(relations)?;
    let fk_sql = foreign_keys_catalog_sql(relations)?;
    assert_read_only_catalog_sql(&rel_sql)?;
    assert_read_only_catalog_sql(&col_sql)?;
    assert_read_only_catalog_sql(&con_sql)?;
    assert_read_only_catalog_sql(&fk_sql)?;

    let rel_rows = catalog_rows(db, connection_string, &rel_sql)?;
    let col_rows = catalog_rows(db, connection_string, &col_sql)?;
    let con_rows = catalog_rows(db, connection_string, &con_sql)?;
    let fk_rows = catalog_rows(db, connection_string, &fk_sql)?;

    let mut out = Vec::new();
    for row in rel_rows {
        let schema = cell(&row, 0);
        let name = cell(&row, 1);
        let kind = cell(&row, 3);
        let is_view = kind == "view" || kind == "materialized_view";
        let (view_definition, view_definition_available) = if is_view {
            match view_definition(db, connection_string, &schema, &name) {
                Ok(Some(sql)) if !sql.trim().is_empty() => (Some(sql), Some(true)),
                Ok(_) => (None, Some(false)),
                Err(_) => (None, Some(false)),
            }
        } else {
            (None, None)
        };
        out.push(PgRelationSnapshot {
            schema,
            name,
            kind,
            catalog_oid: Some(cell(&row, 2)).filter(|s| !s.is_empty()),
            columns: vec![],
            unique_sets: vec![],
            select_ok: cell(&row, 4) == "t",
            insert_ok: cell(&row, 5) == "t",
            update_ok: cell(&row, 6) == "t",
            delete_ok: cell(&row, 7) == "t",
            view_definition,
            view_definition_available,
            foreign_keys: vec![],
        });
    }

    for row in col_rows {
        let schema = cell(&row, 0);
        let name = cell(&row, 1);
        let Some(rel) = out.iter_mut().find(|r| r.schema == schema && r.name == name) else {
            continue;
        };
        let default_raw = cell(&row, 7);
        let identity = cell(&row, 6);
        rel.columns.push(ImportColumn {
            name: cell(&row, 2),
            data_type: cell(&row, 3),
            is_nullable: cell(&row, 4).eq_ignore_ascii_case("YES"),
            ordinal_position: cell(&row, 5).parse().unwrap_or(0),
            is_autogenerated: !identity.eq_ignore_ascii_case("NO")
                || default_raw.to_ascii_lowercase().contains("nextval("),
            is_primary_key: false,
        });
    }

    let mut sets: BTreeMap<(String, String, String), (String, Vec<(i64, String)>)> = BTreeMap::new();
    for row in con_rows {
        let key = (cell(&row, 0), cell(&row, 1), cell(&row, 2));
        let ord: i64 = cell(&row, 5).parse().unwrap_or(0);
        sets.entry(key)
            .or_insert_with(|| (cell(&row, 3), Vec::new()))
            .1
            .push((ord, cell(&row, 4)));
    }
    for ((schema, name, _), (contype, mut cols)) in sets {
        cols.sort_by_key(|(ord, _)| *ord);
        let names: Vec<String> = cols.into_iter().map(|(_, n)| n).collect();
        if let Some(rel) = out.iter_mut().find(|r| r.schema == schema && r.name == name) {
            if contype == "p" {
                for col in &mut rel.columns {
                    if names.iter().any(|n| n == &col.name) {
                        col.is_primary_key = true;
                    }
                }
            }
            rel.unique_sets.push(names);
        }
    }

    let mut fks: BTreeMap<String, (String, String, String, String, Vec<(i64, String, String)>)> =
        BTreeMap::new();
    for row in fk_rows {
        let oid = cell(&row, 6);
        let ord: i64 = cell(&row, 7).parse().unwrap_or(0);
        fks.entry(oid)
            .or_insert_with(|| {
                (
                    cell(&row, 0),
                    cell(&row, 1),
                    cell(&row, 3),
                    cell(&row, 4),
                    Vec::new(),
                )
            })
            .4
            .push((ord, cell(&row, 2), cell(&row, 5)));
    }
    for (_, (fs, fnm, ts, tn, mut cols)) in fks {
        cols.sort_by_key(|(ord, _, _)| *ord);
        let suggestion = FkSuggestion {
            from_schema: fs.clone(),
            from_name: fnm.clone(),
            to_schema: ts,
            to_name: tn,
            from_columns: cols.iter().map(|(_, c, _)| c.clone()).collect(),
            to_columns: cols.iter().map(|(_, _, c)| c.clone()).collect(),
        };
        for rel in &mut out {
            if (rel.schema == suggestion.from_schema && rel.name == suggestion.from_name)
                || (rel.schema == suggestion.to_schema && rel.name == suggestion.to_name)
            {
                rel.foreign_keys.push(suggestion.clone());
            }
        }
    }
    Ok(out)
}

fn view_definition(
    db: &DbSession,
    connection_string: &str,
    schema: &str,
    name: &str,
) -> Result<Option<String>, String> {
    let sql = viewdef_catalog_sql(schema, name);
    assert_read_only_catalog_sql(&sql)?;
    let rows = catalog_rows(db, connection_string, &sql)?;
    Ok(rows.first().map(|r| cell(r, 0)).filter(|s| !s.is_empty()))
}

/// Aggregate NULL / duplicate / overlap counts. Not a row copy.
pub fn diagnose_mapping_relation(
    db: &DbSession,
    connection_string: &str,
    schema: &str,
    table: &str,
    from_columns: &[String],
    output_columns: &[String],
    valid_from: Option<&str>,
    valid_to: Option<&str>,
) -> Result<dwh_pipeline::pg_import::MappingKeyDiagnosis, String> {
    let packed = diagnose_mapping_sql(
        schema,
        table,
        from_columns,
        output_columns,
        valid_from,
        valid_to,
    )?;
    let mut parts = packed.split("\n--SPLIT--\n");
    let head = parts.next().unwrap_or("");
    let rows = catalog_rows(db, connection_string, head)?;
    let row = rows.first().cloned().unwrap_or_default();
    let null_from = cell(&row, 0).parse().unwrap_or(0);
    let duplicate_from_groups = cell(&row, 1).parse().unwrap_or(0);
    let null_outputs = cell(&row, 2).parse().unwrap_or(0);
    let overlapping_pairs = if let Some(overlap_sql) = parts.next() {
        let overlap_rows = catalog_rows(db, connection_string, overlap_sql)?;
        Some(
            overlap_rows
                .first()
                .map(|r| cell(r, 0).parse().unwrap_or(0))
                .unwrap_or(0),
        )
    } else {
        None
    };
    let mut notes = Vec::new();
    if null_from > 0 {
        notes.push(format!("NULL From: {null_from}"));
    }
    if duplicate_from_groups > 0 {
        notes.push(format!("duplicate From groups: {duplicate_from_groups}"));
    }
    if null_outputs > 0 {
        notes.push(format!("NULL outputs: {null_outputs}"));
    }
    if let Some(n) = overlapping_pairs {
        if n > 0 {
            notes.push(format!("overlapping intervals: {n}"));
        }
    }
    Ok(dwh_pipeline::pg_import::MappingKeyDiagnosis {
        null_from,
        duplicate_from_groups,
        null_outputs,
        overlapping_pairs,
        notes,
    })
}

fn catalog_rows(
    db: &DbSession,
    connection_string: &str,
    remote_sql: &str,
) -> Result<Vec<Vec<Option<String>>>, String> {
    assert_read_only_catalog_sql(remote_sql)?;
    let conn_str = connection_string.trim();
    with_postgres_query(db, conn_str, remote_sql, |conn, sql| {
        let mut stmt = conn
            .prepare(&sql)
            .map_err(|e| redact_conn_err(conn_str, e))?;
        let mut rows = stmt
            .query(params![])
            .map_err(|e| redact_conn_err(conn_str, e))?;
        let mut out = Vec::new();
        while let Some(row) = rows.next().map_err(|e| redact_conn_err(conn_str, e))? {
            let mut cols = Vec::new();
            let mut i = 0;
            loop {
                match row.get::<_, Option<String>>(i) {
                    Ok(v) => cols.push(v),
                    Err(_) => break,
                }
                i += 1;
                if i > 32 {
                    break;
                }
            }
            out.push(cols);
        }
        Ok(out)
    })
}

fn cell(row: &[Option<String>], idx: usize) -> String {
    row.get(idx).and_then(|v| v.clone()).unwrap_or_default()
}

