pub fn schema_fingerprint(cols: &[ImportColumn]) -> String {
    let mut lines = String::new();
    for c in cols {
        lines.push_str(&format!(
            "{}\t{}\t{}\t{}\t{}\t{}\n",
            c.name,
            c.data_type,
            c.is_nullable as u8,
            c.ordinal_position,
            c.is_autogenerated as u8,
            c.is_primary_key as u8
        ));
    }
    sha256_hex(&lines)
}

