pub fn default_prefixes() -> Vec<String> {
    vec!["map_".into(), "_map_".into()]
}

fn sha256_hex(data: &str) -> String {
    hex::encode(Sha256::digest(data.as_bytes()))
}

/// Literal prefix. `_` is not a wildcard.
pub fn name_matches_prefix(name: &str, prefixes: &[String]) -> bool {
    prefixes
        .iter()
        .any(|p| !p.is_empty() && name.starts_with(p.as_str()))
}

pub fn rule_matches(
    name: &str,
    schema: &str,
    prefixes: &[String],
    rule_schemas: &[String],
) -> bool {
    if !rule_schemas.is_empty() && !rule_schemas.iter().any(|s| s == schema) {
        return false;
    }
    name_matches_prefix(name, prefixes)
}

#[derive(Serialize, Deserialize, Debug, Clone, Copy, PartialEq, Eq, Default)]
#[serde(rename_all = "snake_case")]
pub enum MappingDecision {
    #[default]
    FollowRule,
    Force,
    Exclude,
}

/// Saved decision wins over the name rule. `chosen` is what the wizard will send.
pub fn effective_decision(saved: Option<MappingDecision>, rule: bool) -> MappingDecision {
    match saved.unwrap_or(MappingDecision::FollowRule) {
        MappingDecision::Force => MappingDecision::Force,
        MappingDecision::Exclude => MappingDecision::Exclude,
        MappingDecision::FollowRule => {
            if rule {
                MappingDecision::Force
            } else {
                MappingDecision::FollowRule
            }
        }
    }
}

pub fn is_mapping_candidate(decision: MappingDecision, rule: bool) -> bool {
    match decision {
        MappingDecision::Force => true,
        MappingDecision::Exclude => false,
        MappingDecision::FollowRule => rule,
    }
}

