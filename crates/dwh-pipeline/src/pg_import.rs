pub fn import_fingerprint(project: &Project) -> String {
    let mut redacted = project.clone();
    redacted.root_path = None;
    for c in &mut redacted.connections {
        if let Some(pg) = &mut c.postgres {
            pg.connection_string.clear();
        }
        if let Some(s3) = &mut c.s3 {
            s3.access_key_id = None;
            s3.secret_access_key = None;
            s3.session_token = None;
        }
    }
    for src in &mut redacted.sources {
        src.connection_string = None;
    }
    for map in &mut redacted.workspace.key_maps {
        if matches!(map.storage, KeyMapStorage::Source { .. }) {
            map.entries.clear();
        }
    }
    sha256_hex(&serde_json::to_string(&redacted).unwrap_or_default())
}

pub fn assert_read_only_catalog_sql(sql: &str) -> Result<(), String> {
    let upper = format!(" {sql} ");
    let upper = upper.to_ascii_uppercase();
    for kw in [
        " INSERT ",
        " UPDATE ",
        " DELETE ",
        " DROP ",
        " CREATE ",
        " ALTER ",
        " TRUNCATE ",
        " REFRESH ",
        " GRANT ",
        " REVOKE ",
        " COMMENT ",
    ] {
        if upper.contains(kw) {
            return Err(format!("catalog SQL is not read-only ({kw})"));
        }
    }
    let trimmed = sql.trim_start();
    if !trimmed.starts_with("SELECT") && !trimmed.starts_with("select") {
        return Err("catalog SQL must be a SELECT".into());
    }
    Ok(())
}

fn pair_list(pairs: &[(String, String)]) -> Result<String, String> {
    if pairs.is_empty() {
        return Err("select at least one relation".into());
    }
    let mut parts = Vec::new();
    for (schema, name) in pairs {
        if schema.trim().is_empty() || name.trim().is_empty() {
            return Err("schema and relation name are required".into());
        }
        parts.push(format!(
            "('{}','{}')",
            escape_sql_string(schema),
            escape_sql_string(name)
        ));
    }
    Ok(parts.join(","))
}

pub fn relations_catalog_sql(pairs: &[(String, String)]) -> Result<String, String> {
    let list = pair_list(pairs)?;
    Ok(format!(
        "SELECT n.nspname::text, c.relname::text, c.oid::text, \
CASE c.relkind \
  WHEN 'r' THEN 'table' \
  WHEN 'p' THEN 'partitioned_table' \
  WHEN 'v' THEN 'view' \
  WHEN 'm' THEN 'materialized_view' \
  WHEN 'f' THEN 'foreign' \
  ELSE 'other' \
END, \
CASE WHEN has_table_privilege(c.oid, 'SELECT') THEN 't' ELSE 'f' END, \
CASE WHEN has_table_privilege(c.oid, 'INSERT') THEN 't' ELSE 'f' END, \
CASE WHEN has_table_privilege(c.oid, 'UPDATE') THEN 't' ELSE 'f' END, \
CASE WHEN has_table_privilege(c.oid, 'DELETE') THEN 't' ELSE 'f' END \
FROM pg_catalog.pg_class c \
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace \
WHERE (n.nspname, c.relname) IN ({list}) \
ORDER BY 1, 2"
    ))
}

pub fn columns_catalog_sql(pairs: &[(String, String)]) -> Result<String, String> {
    let list = pair_list(pairs)?;
    Ok(format!(
        "SELECT table_schema::text, table_name::text, column_name::text, data_type::text, \
is_nullable::text, ordinal_position::text, \
COALESCE(is_identity, 'NO')::text, COALESCE(column_default, '')::text \
FROM information_schema.columns \
WHERE (table_schema, table_name) IN ({list}) \
ORDER BY table_schema, table_name, ordinal_position"
    ))
}

pub fn constraints_catalog_sql(pairs: &[(String, String)]) -> Result<String, String> {
    let list = pair_list(pairs)?;
    Ok(format!(
        "SELECT n.nspname::text, t.relname::text, c.oid::text, c.contype::text, \
a.attname::text, u.ord::text \
FROM pg_catalog.pg_constraint c \
JOIN pg_catalog.pg_class t ON t.oid = c.conrelid \
JOIN pg_catalog.pg_namespace n ON n.oid = t.relnamespace \
JOIN LATERAL unnest(c.conkey) WITH ORDINALITY AS u(attnum, ord) ON true \
JOIN pg_catalog.pg_attribute a ON a.attrelid = t.oid AND a.attnum = u.attnum \
WHERE c.contype IN ('p','u') \
AND (n.nspname, t.relname) IN ({list}) \
ORDER BY 1, 2, 3, u.ord"
    ))
}

pub fn foreign_keys_catalog_sql(pairs: &[(String, String)]) -> Result<String, String> {
    let list = pair_list(pairs)?;
    Ok(format!(
        "SELECT n1.nspname::text, t1.relname::text, a1.attname::text, \
n2.nspname::text, t2.relname::text, a2.attname::text, c.oid::text, u.ord::text \
FROM pg_catalog.pg_constraint c \
JOIN pg_catalog.pg_class t1 ON t1.oid = c.conrelid \
JOIN pg_catalog.pg_namespace n1 ON n1.oid = t1.relnamespace \
JOIN pg_catalog.pg_class t2 ON t2.oid = c.confrelid \
JOIN pg_catalog.pg_namespace n2 ON n2.oid = t2.relnamespace \
JOIN LATERAL unnest(c.conkey, c.confkey) WITH ORDINALITY AS u(src, dst, ord) ON true \
JOIN pg_catalog.pg_attribute a1 ON a1.attrelid = t1.oid AND a1.attnum = u.src \
JOIN pg_catalog.pg_attribute a2 ON a2.attrelid = t2.oid AND a2.attnum = u.dst \
WHERE c.contype = 'f' \
AND ((n1.nspname, t1.relname) IN ({list}) OR (n2.nspname, t2.relname) IN ({list})) \
ORDER BY c.oid, u.ord"
    ))
}

