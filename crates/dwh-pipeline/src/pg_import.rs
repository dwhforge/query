fn quote_ident(ident: &str) -> String {
    format!("\"{}\"", ident.replace('"', "\"\""))
}

pub fn diagnose_mapping_sql(
    schema: &str,
    table: &str,
    from_columns: &[String],
    output_columns: &[String],
    valid_from: Option<&str>,
    valid_to: Option<&str>,
) -> Result<String, String> {
    if from_columns.is_empty() || output_columns.is_empty() {
        return Err("diagnosis needs From and output columns".into());
    }
    let rel = format!("{}.{}", quote_ident(schema), quote_ident(table));
    let null_from = from_columns
        .iter()
        .map(|c| format!("{} IS NULL", quote_ident(c)))
        .collect::<Vec<_>>()
        .join(" OR ");
    let distinct = from_columns
        .iter()
        .map(|c| quote_ident(c))
        .collect::<Vec<_>>()
        .join(", ");
    let null_out = output_columns
        .iter()
        .map(|c| format!("{} IS NULL", quote_ident(c)))
        .collect::<Vec<_>>()
        .join(" OR ");
    // Group count, not extra-row count. Range SCD groups by From + valid_from so
    // several non-overlapping versions of one From are not duplicates.
    let (dup_group, bounds) = if let (Some(vf), Some(vt)) = (valid_from, valid_to) {
        (
            format!(
                "(SELECT COUNT(*) FROM ( \
SELECT 1 FROM {rel} GROUP BY {distinct}, {vf} HAVING COUNT(*) > 1 \
) dwh_dup_groups)",
                vf = quote_ident(vf)
            ),
            format!(
                "COUNT(*) FILTER (WHERE {vf} IS NULL OR ({vt} IS NOT NULL AND {vf}::timestamp >= {vt}::timestamp))",
                vf = quote_ident(vf),
                vt = quote_ident(vt)
            ),
        )
    } else {
        (
            format!(
                "(SELECT COUNT(*) FROM ( \
SELECT 1 FROM {rel} GROUP BY {distinct} HAVING COUNT(*) > 1 \
) dwh_dup_groups)"
            ),
            "0".to_string(),
        )
    };
    let head = format!(
        "SELECT \
COUNT(*) FILTER (WHERE {null_from})::text, \
{dup_group}::text, \
COUNT(*) FILTER (WHERE {null_out})::text, \
({bounds})::text \
FROM {rel}"
    );
    if let (Some(vf), Some(vt)) = (valid_from, valid_to) {
        let eqs = from_columns
            .iter()
            .map(|c| {
                format!(
                    "a.{} IS NOT DISTINCT FROM b.{}",
                    quote_ident(c),
                    quote_ident(c)
                )
            })
            .collect::<Vec<_>>()
            .join(" AND ");
        let overlap = format!(
            "SELECT COUNT(*)::text FROM ( \
SELECT 1 FROM {rel} a JOIN {rel} b ON {eqs} AND a.ctid < b.ctid \
AND a.{vf}::timestamp < COALESCE(b.{vt}::timestamp, 'infinity'::timestamp) \
AND b.{vf}::timestamp < COALESCE(a.{vt}::timestamp, 'infinity'::timestamp) \
) dwh_overlap",
            vf = quote_ident(vf),
            vt = quote_ident(vt),
        );
        assert_read_only_catalog_sql(&head)?;
        assert_read_only_catalog_sql(&overlap)?;
        return Ok(format!("{head}\n--SPLIT--\n{overlap}"));
    }
    assert_read_only_catalog_sql(&head)?;
    Ok(head)
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq, Default)]
pub struct MappingKeyDiagnosis {
    pub null_from: i64,
    pub duplicate_from_groups: i64,
    pub null_outputs: i64,
    pub overlapping_pairs: Option<i64>,
    pub notes: Vec<String>,
}

/// Notes for a diagnosis. Range SCD does not treat another version of the same From as a duplicate.
pub fn diagnosis_notes(
    temporal: bool,
    null_from: i64,
    duplicate_groups: i64,
    null_outputs: i64,
    invalid_bounds: i64,
    overlapping_pairs: Option<i64>,
) -> Vec<String> {
    let mut notes = Vec::new();
    if null_from > 0 {
        notes.push(format!("NULL From: {null_from}"));
    }
    if duplicate_groups > 0 {
        if temporal {
            notes.push(format!("duplicate From+valid_from: {duplicate_groups}"));
        } else {
            notes.push(format!("duplicate From groups: {duplicate_groups}"));
        }
    }
    if null_outputs > 0 {
        notes.push(format!("NULL outputs: {null_outputs}"));
    }
    if temporal && invalid_bounds > 0 {
        notes.push(format!("invalid SCD bounds: {invalid_bounds}"));
    }
    if let Some(n) = overlapping_pairs {
        if n > 0 {
            notes.push(format!("overlapping intervals: {n}"));
        }
    }
    notes
}

/// Warehouse write gate for an imported relation. `None` means this map is not import-governed.
pub fn import_write_refusal(registry: Option<&PgImportRegistry>, map_id: &str) -> Option<String> {
    let reg = registry?;
    let rec = reg
        .relations
        .iter()
        .find(|r| r.keymap_id.as_deref() == Some(map_id))?;
    if rec.binding_status == BindingStatus::Broken {
        return Some("broken import binding — warehouse write refused".into());
    }
    if !rec.write_back {
        return Some("import write-back is not allowed for this relation".into());
    }
    None
}

fn canon_unique_sets(sets: &[Vec<String>]) -> Vec<Vec<String>> {
    let mut out: Vec<Vec<String>> = sets
        .iter()
        .map(|set| {
            let mut cols: Vec<String> = set.iter().map(|c| c.to_ascii_lowercase()).collect();
            cols.sort();
            cols
        })
        .collect();
    out.sort();
    out
}

/// Copy uniqueness and privileges from the fresh catalog onto the plan before the fold.
pub fn adopt_fresh_write_metadata(plan: &mut PgImportPlan, fresh: &[PgRelationSnapshot]) {
    for rel in &mut plan.relations {
        if !rel.present {
            continue;
        }
        let Some(snap) = fresh
            .iter()
            .find(|s| s.schema == rel.schema && s.name == rel.name)
        else {
            continue;
        };
        rel.unique_sets = snap.unique_sets.clone();
        rel.select_ok = snap.select_ok;
        rel.insert_ok = snap.insert_ok;
        rel.update_ok = snap.update_ok;
        rel.delete_ok = snap.delete_ok;
    }
}

pub fn metadata_matches(plan: &PgImportPlan, fresh: &[PgRelationSnapshot]) -> Result<(), String> {
    for rel in &plan.relations {
        let found = fresh
            .iter()
            .find(|s| s.schema == rel.schema && s.name == rel.name);
        if !rel.present {
            if found.is_some() {
                return Err(format!(
                    "metadata changed — {}.{} is present again; review again",
                    rel.schema, rel.name
                ));
            }
            continue;
        }
        let Some(snap) = found else {
            return Err(format!(
                "metadata changed — {}.{} is gone; review again",
                rel.schema, rel.name
            ));
        };
        if snap.kind != rel.kind || snap.fingerprint() != rel.schema_fingerprint {
            return Err(format!(
                "metadata changed — {}.{} schema fingerprint differs; review again",
                rel.schema, rel.name
            ));
        }
        if snap.catalog_oid != rel.catalog_oid {
            return Err(format!(
                "metadata changed — {}.{} catalog identity differs; review again",
                rel.schema, rel.name
            ));
        }
        if snap.view_definition_available != rel.view_definition_available
            || snap.view_definition != rel.view_definition
        {
            return Err(format!(
                "metadata changed — {}.{} view definition differs; review again",
                rel.schema, rel.name
            ));
        }
        if canon_unique_sets(&snap.unique_sets) != canon_unique_sets(&rel.unique_sets) {
            return Err(format!(
                "metadata changed — {}.{} unique constraints differ; review again",
                rel.schema, rel.name
            ));
        }
        if snap.select_ok != rel.select_ok
            || snap.insert_ok != rel.insert_ok
            || snap.update_ok != rel.update_ok
            || snap.delete_ok != rel.delete_ok
        {
            return Err(format!(
                "metadata changed — {}.{} privileges differ; review again",
                rel.schema, rel.name
            ));
        }
    }
    Ok(())
}

pub fn commit_pg_import(project: &Project, plan: &PgImportPlan) -> Result<PgImportOutcome, String> {
    if plan.commit_token.trim().is_empty() {
        return Err("commit token is required".into());
    }
    if let Some(reg) = &project.pg_import {
        if reg.applied_tokens.iter().any(|t| t == &plan.commit_token) {
            return Ok(empty_outcome(project.clone(), true));
        }
    }
    if import_fingerprint(project) != plan.expected_fingerprint {
        return Err("stale plan — review again".into());
    }
    let conn = project
        .connections
        .iter()
        .find(|c| c.id == plan.connection_id)
        .ok_or_else(|| format!("connection '{}' was not found", plan.connection_id))?;
    if conn.kind != ConnectionKind::Postgres {
        return Err("import requires a postgres connection".into());
    }
    let prepared = prepare_actions(project, plan)?;
    Ok(apply_actions(project, plan, prepared))
}

fn empty_outcome(project: Project, already: bool) -> PgImportOutcome {
    PgImportOutcome {
        project,
        already_applied: already,
        created_query_ids: vec![],
        reused_query_ids: vec![],
        created_map_ids: vec![],
        warnings: vec![],
        focus_query_id: None,
        focus_step_index: None,
        open_join_lens: false,
        touched_map_ids: vec![],
    }
}

struct Prepared {
    warnings: Vec<String>,
    focus_query_id: Option<String>,
    focus_step_index: Option<u32>,
    open_join_lens: bool,
}

fn prepare_actions(project: &Project, plan: &PgImportPlan) -> Result<Prepared, String> {
    let mut warnings = Vec::new();
    let mut final_maps: BTreeMap<(String, String), (String, Vec<String>, ImportTimeMode)> =
        BTreeMap::new();
    for rel in &plan.relations {
        let existing = find_imported(project, &plan.connection_id, &rel.schema, &rel.name);
        if let Some(rec) = existing {
            if binding_would_change(project, rec, rel) {
                if let Some(id) = &rec.keymap_id {
                    if plan.save_in_flight_map_ids.iter().any(|x| x == id) {
                        return Err(
                            "Save is in flight — wait before changing this mapping binding"
                                .into(),
                        );
                    }
                    if plan.dirty_map_ids.iter().any(|x| x == id) && !plan.discard_confirmed {
                        return Err(
                            "unsaved map edits — confirm discard before changing the binding"
                                .into(),
                        );
                    }
                }
            }
        }
        if let Some((id, from, mode)) = planned_map_identity(project, plan, rel, &mut warnings) {
            final_maps.insert((rel.schema.clone(), rel.name.clone()), (id, from, mode));
        }
    }
    let (focus_query_id, focus_step_index, open_join_lens) = match &plan.working_query {
        None => (None, None, false),
        Some(wq) => {
            if wq.token.trim().is_empty() {
                return Err("working query token is required".into());
            }
            if let Some(reg) = &project.pg_import {
                if let Some(prev) = reg.working_queries.iter().find(|w| w.token == wq.token) {
                    if project.workspace.query(&prev.query_id).is_some() {
                        warnings.push(format!(
                            "analysis query '{}' already exists",
                            prev.query_id
                        ));
                        let q = project.workspace.query(&prev.query_id).unwrap();
                        let join_at = q.steps.iter().position(|s| {
                            matches!(s, TransformationStep::Join { .. })
                        });
                        let open = join_at.is_some();
                        let idx = join_at.unwrap_or(q.steps.len().saturating_sub(1)) as u32;
                        return Ok(Prepared {
                            warnings,
                            focus_query_id: Some(prev.query_id.clone()),
                            focus_step_index: Some(idx),
                            open_join_lens: open,
                        });
                    }
                }
            }
            validate_working(project, plan, wq, &final_maps)?;
            let has_join = wq.right_query_id.is_some() || wq.right_relation.is_some();
            (Some(String::new()), None, has_join)
        }
    };
    Ok(Prepared {
        warnings,
        focus_query_id,
        focus_step_index,
        open_join_lens,
    })
}

fn validate_working(
    project: &Project,
    plan: &PgImportPlan,
    wq: &PlannedWorkingQuery,
    maps: &BTreeMap<(String, String), (String, Vec<String>, ImportTimeMode)>,
) -> Result<(), String> {
    resolve_query_ref(project, plan, wq.left_query_id.as_deref(), wq.left_relation.as_ref())
        .ok_or_else(|| "working query: left query was not found".to_string())?;
    let (map_id, from, mode) = maps
        .get(&wq.map_relation)
        .ok_or_else(|| "working query: map is not a confirmed binding".to_string())?;
    if wq.input_columns.len() != from.len() || wq.input_columns.iter().any(|c| c.trim().is_empty())
    {
        return Err("working query: input bindings must match From".into());
    }
    if wq.output_bindings.is_empty() {
        return Err("working query: choose at least one output binding".into());
    }
    let mut dests = BTreeSet::new();
    let map = project.workspace.key_map(map_id);
    let outputs = if let Some(m) = map {
        m.output_columns_eff()
    } else {
        plan.relations
            .iter()
            .find(|r| r.schema == wq.map_relation.0 && r.name == wq.map_relation.1)
            .and_then(|r| r.confirmed.as_ref())
            .map(|b| b.output_columns.clone())
            .unwrap_or_default()
    };
    for b in &wq.output_bindings {
        if b.map_column.trim().is_empty() || b.destination_column.trim().is_empty() {
            return Err("working query: output binding is incomplete".into());
        }
        if !outputs.iter().any(|c| c == &b.map_column) {
            return Err(format!(
                "working query: '{}' is not a map output",
                b.map_column
            ));
        }
        if !dests.insert(b.destination_column.to_ascii_lowercase()) {
            return Err("working query: duplicate destination column".into());
        }
    }
    if matches!(mode, ImportTimeMode::RangeScd)
        && wq.as_of_column.as_deref().unwrap_or("").trim().is_empty()
    {
        return Err("working query: range map needs an as-of column".into());
    }
    let _ = map_id;
    if wq.right_query_id.is_some() || wq.right_relation.is_some() {
        resolve_query_ref(
            project,
            plan,
            wq.right_query_id.as_deref(),
            wq.right_relation.as_ref(),
        )
        .ok_or_else(|| "working query: right query was not found".to_string())?;
        let mut left_on = wq.left_on.clone();
        let mut right_on = wq.right_on.clone();
        for eq in &wq.extra_equalities {
            left_on.push(eq.left.clone());
            right_on.push(eq.right.clone());
        }
        if left_on.is_empty() || left_on.len() != right_on.len() {
            return Err("working query: Join needs paired columns".into());
        }
        if left_on.iter().any(|c| c.trim().is_empty()) || right_on.iter().any(|c| c.trim().is_empty())
        {
            return Err("working query: Join column is empty".into());
        }
        parse_join_type(wq.join_type.as_deref())?;
    }
    Ok(())
}

fn parse_join_type(raw: Option<&str>) -> Result<JoinType, String> {
    match raw.unwrap_or("left").trim().to_ascii_lowercase().as_str() {
        "inner" => Ok(JoinType::Inner),
        "left" | "" => Ok(JoinType::Left),
        "right" => Ok(JoinType::Right),
        "full" => Ok(JoinType::Full),
        other => Err(format!("working query: unknown join type '{other}'")),
    }
}

fn resolve_query_ref(
    project: &Project,
    plan: &PgImportPlan,
    query_id: Option<&str>,
    relation: Option<&(String, String)>,
) -> Option<String> {
    if let Some(id) = query_id {
        if project.workspace.query(id).is_some() {
            return Some(id.to_string());
        }
    }
    if let Some((schema, name)) = relation {
        if let Some(rec) = find_imported(project, &plan.connection_id, schema, name) {
            if project.workspace.query(&rec.query_id).is_some() {
                return Some(rec.query_id.clone());
            }
        }
        if plan
            .relations
            .iter()
            .any(|r| r.present && &r.schema == schema && &r.name == name)
        {
            return Some(format!("pending:{schema}.{name}"));
        }
    }
    None
}

fn planned_map_identity(
    project: &Project,
    plan: &PgImportPlan,
    rel: &PlannedRelation,
    warnings: &mut Vec<String>,
) -> Option<(String, Vec<String>, ImportTimeMode)> {
    if !rel.present || !wants_map(rel) {
        return None;
    }
    let Some(binding) = rel.confirmed.as_ref() else {
        warnings.push(format!(
            "{}.{} left as a query — binding was not confirmed",
            rel.schema, rel.name
        ));
        return None;
    };
    if !column_issues(rel, binding).is_empty() {
        return None;
    }
    let existing = find_imported(project, &plan.connection_id, &rel.schema, &rel.name);
    let id = existing
        .and_then(|r| r.keymap_id.clone())
        .unwrap_or_else(|| "pending-map".into());
    Some((id, binding.from_columns.clone(), binding.time_mode))
}

fn wants_map(rel: &PlannedRelation) -> bool {
    rel.present
        && !matches!(rel.mapping_decision, MappingDecision::Exclude)
        && rel.confirmed.is_some()
}

fn column_issues(rel: &PlannedRelation, binding: &ConfirmedBinding) -> Vec<String> {
    let mut issues = Vec::new();
    if !rel.present {
        issues.push(format!("{}.{} is unavailable", rel.schema, rel.name));
        return issues;
    }
    let mut seen_names: BTreeMap<String, usize> = BTreeMap::new();
    for c in &rel.columns {
        *seen_names.entry(c.name.to_ascii_lowercase()).or_insert(0) += 1;
    }
    for (n, count) in &seen_names {
        if *count > 1 {
            issues.push(format!("ambiguous column '{n}'"));
        }
    }
    if binding.from_columns.is_empty() || binding.output_columns.is_empty() {
        issues.push("From and outputs are required".into());
    }
    let mut roles: BTreeMap<String, String> = BTreeMap::new();
    let mut take = |names: &[String], role: &str, issues: &mut Vec<String>| {
        for name in names {
            let key = name.trim().to_ascii_lowercase();
            if key.is_empty() {
                issues.push(format!("{role} column is empty"));
                continue;
            }
            if let Some(prev) = roles.insert(key.clone(), role.to_string()) {
                issues.push(format!("column '{name}' is both {prev} and {role}"));
            }
            match resolve_catalog_name(&rel.columns, name) {
                Ok(_) => {}
                Err(e) => issues.push(e),
            }
        }
    };
    take(&binding.from_columns, "From", &mut issues);
    take(&binding.output_columns, "output", &mut issues);
    take(&binding.editable_columns, "attr", &mut issues);
    if matches!(binding.time_mode, ImportTimeMode::RangeScd) {
        let vf = binding.valid_from_column.clone().unwrap_or_default();
        let vt = binding.valid_to_column.clone().unwrap_or_default();
        take(&[vf], "valid_from", &mut issues);
        take(&[vt], "valid_to", &mut issues);
    }
    issues
}

fn resolve_catalog_name(cols: &[ImportColumn], name: &str) -> Result<String, String> {
    let hits: Vec<_> = cols
        .iter()
        .filter(|c| c.name.eq_ignore_ascii_case(name.trim()))
        .collect();
    match hits.len() {
        1 => Ok(hits[0].name.clone()),
        0 => Err(format!("column '{}' is not on the relation", name.trim())),
        _ => Err(format!("column '{}' is ambiguous", name.trim())),
    }
}

fn write_back_refusal(rel: &PlannedRelation, binding: &ConfirmedBinding) -> Option<String> {
    if rel.kind != "table" && rel.kind != "partitioned_table" {
        return Some("write-back is only available for tables".into());
    }
    if !(rel.insert_ok && rel.update_ok && rel.delete_ok) {
        return Some("INSERT, UPDATE, and DELETE privileges are required".into());
    }
    let mut key = binding.from_columns.clone();
    if matches!(binding.time_mode, ImportTimeMode::RangeScd) {
        key.push(binding.valid_from_column.clone().unwrap_or_default());
    }
    let want: BTreeSet<_> = key.iter().map(|s| s.to_ascii_lowercase()).collect();
    let ok = rel.unique_sets.iter().any(|set| {
        let got: BTreeSet<_> = set.iter().map(|s| s.to_ascii_lowercase()).collect();
        got == want
    });
    if !ok {
        return Some("no unique constraint matches the row identity".into());
    }
    None
}

fn binding_would_change(project: &Project, rec: &ImportedRelation, rel: &PlannedRelation) -> bool {
    let Some(id) = &rec.keymap_id else {
        return wants_map(rel) && rel.confirmed.is_some();
    };
    let Some(map) = project.workspace.key_map(id) else {
        return true;
    };
    let Some(binding) = rel.confirmed.as_ref() else {
        return wants_map(rel);
    };
    if !wants_map(rel) {
        return true;
    }
    map.from_columns_eff() != binding.from_columns
        || map.output_columns_eff() != binding.output_columns
        || map.editable_columns != binding.editable_columns
        || rec.write_back != binding.write_back
        || (matches!(binding.time_mode, ImportTimeMode::RangeScd) != map.is_range_scd())
}

fn find_imported<'a>(
    project: &'a Project,
    connection_id: &str,
    schema: &str,
    name: &str,
) -> Option<&'a ImportedRelation> {
    project.pg_import.as_ref().and_then(|reg| {
        reg.relations.iter().find(|r| {
            r.connection_id == connection_id && r.schema == schema && r.name == name
        })
    })
}

fn apply_actions(project: &Project, plan: &PgImportPlan, prepared: Prepared) -> PgImportOutcome {
    let mut next = project.clone();
    let mut warnings = prepared.warnings;
    warnings.push("PostgreSQL was not modified".into());
    let mut created_query_ids = Vec::new();
    let mut reused_query_ids = Vec::new();
    let mut created_map_ids = Vec::new();
    let mut touched_map_ids = Vec::new();
    let mut reg = next.pg_import.clone().unwrap_or_default();
    reg.prefixes = plan.prefixes.clone();
    reg.rule_schemas = plan.rule_schemas.clone();

    let mut taken = taken_ids(&next);
    let mut query_by_rel: BTreeMap<(String, String), String> = BTreeMap::new();
    let mut map_by_rel: BTreeMap<(String, String), String> = BTreeMap::new();

    for rel in &plan.relations {
        let key = (rel.schema.clone(), rel.name.clone());
        let prior = reg.relations.iter().find(|r| {
            r.connection_id == plan.connection_id && r.schema == rel.schema && r.name == rel.name
        });
        if !rel.present {
            if let Some(rec) = prior.cloned() {
                let mut rec = rec;
                rec.binding_status = BindingStatus::Broken;
                rec.binding_issues = vec![format!(
                    "{}.{} is unavailable (dropped or renamed; not remapped)",
                    rel.schema, rel.name
                )];
                upsert_relation(&mut reg, rec);
                warnings.push(format!("{}.{} is unavailable", rel.schema, rel.name));
            }
            continue;
        }
        let source_id = ensure_source(&mut next, &mut taken, &plan.connection_id, rel, prior);
        let (query_id, created_q) =
            ensure_query(&mut next, &mut taken, &plan.connection_id, rel, prior);
        if created_q {
            created_query_ids.push(query_id.clone());
        } else {
            reused_query_ids.push(query_id.clone());
        }
        query_by_rel.insert(key.clone(), query_id.clone());

        let (keymap_id, status, issues, write_back) =
            ensure_map(&mut next, &mut taken, plan, rel, prior, &mut warnings, &mut touched_map_ids, &mut created_map_ids);
        if let Some(id) = &keymap_id {
            map_by_rel.insert(key.clone(), id.clone());
        }
        let record = ImportedRelation {
            id: prior
                .map(|r| r.id.clone())
                .unwrap_or_else(|| fresh_id("imp", &format!("{}_{}", rel.schema, rel.name), &mut taken)),
            connection_id: plan.connection_id.clone(),
            schema: rel.schema.clone(),
            name: rel.name.clone(),
            kind: rel.kind.clone(),
            catalog_oid: rel.catalog_oid.clone(),
            schema_fingerprint: rel.schema_fingerprint.clone(),
            source_id,
            query_id,
            keymap_id,
            mapping_decision: rel.mapping_decision,
            binding_status: status,
            binding_issues: issues,
            quality_notes: rel.quality_notes.clone(),
            write_back,
            view_definition: rel.view_definition.clone(),
            view_definition_available: rel.view_definition_available,
        };
        upsert_relation(&mut reg, record);
    }

    let mut focus_query_id = prepared.focus_query_id.clone();
    let mut focus_step_index = prepared.focus_step_index;
    let mut open_join_lens = prepared.open_join_lens;
    if let Some(wq) = &plan.working_query {
        let already = reg
            .working_queries
            .iter()
            .find(|w| w.token == wq.token)
            .map(|w| w.query_id.clone());
        if let Some(id) = already {
            if next.workspace.query(&id).is_some() {
                focus_query_id = Some(id);
            }
        } else if let Some(built) = build_working_query(&mut next, &mut taken, plan, wq, &query_by_rel, &map_by_rel)
        {
            let id = built.id.clone();
            let join_at = built.steps.iter().position(|s| matches!(s, TransformationStep::Join { .. }));
            open_join_lens = join_at.is_some();
            focus_step_index = Some(join_at.unwrap_or(built.steps.len().saturating_sub(1)) as u32);
            next.workspace.queries.push(built);
            created_query_ids.push(id.clone());
            reg.working_queries.push(RecordedWorkingQuery {
                token: wq.token.clone(),
                query_id: id.clone(),
            });
            focus_query_id = Some(id);
        }
    }
    if next.workspace.focus_query_id.is_empty() {
        if let Some(id) = focus_query_id.clone().or_else(|| created_query_ids.first().cloned()) {
            next.workspace.focus_query_id = id;
        }
    } else if let Some(id) = &focus_query_id {
        next.workspace.focus_query_id = id.clone();
    }
    reg.applied_tokens.push(plan.commit_token.clone());
    next.pg_import = Some(reg);
    next.format_version = crate::project::PROJECT_FORMAT_VERSION;
    PgImportOutcome {
        project: next,
        already_applied: false,
        created_query_ids,
        reused_query_ids,
        created_map_ids,
        warnings,
        focus_query_id,
        focus_step_index,
        open_join_lens,
        touched_map_ids,
    }
}

fn upsert_relation(reg: &mut PgImportRegistry, rec: ImportedRelation) {
    if let Some(slot) = reg.relations.iter_mut().find(|r| {
        r.connection_id == rec.connection_id && r.schema == rec.schema && r.name == rec.name
    }) {
        *slot = rec;
    } else {
        reg.relations.push(rec);
    }
}

fn taken_ids(project: &Project) -> HashSet<String> {
    let mut ids = HashSet::new();
    for s in &project.sources {
        ids.insert(s.id.clone());
    }
    for q in &project.workspace.queries {
        ids.insert(q.id.clone());
    }
    for m in &project.workspace.key_maps {
        ids.insert(m.id.clone());
    }
    if let Some(reg) = &project.pg_import {
        for r in &reg.relations {
            ids.insert(r.id.clone());
        }
    }
    ids
}

fn slug(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let out = out.trim_matches('_').to_string();
    if out.is_empty() {
        "item".into()
    } else {
        out
    }
}

fn fresh_id(prefix: &str, hint: &str, taken: &mut HashSet<String>) -> String {
    let base = format!("{prefix}_{}", slug(hint));
    let mut id = base.clone();
    let mut n = 2;
    while taken.contains(&id) {
        id = format!("{base}_{n}");
        n += 1;
    }
    taken.insert(id.clone());
    id
}

fn ensure_source(
    project: &mut Project,
    taken: &mut HashSet<String>,
    connection_id: &str,
    rel: &PlannedRelation,
    prior: Option<&ImportedRelation>,
) -> String {
    if let Some(rec) = prior {
        if project.sources.iter().any(|s| s.id == rec.source_id) {
            return rec.source_id.clone();
        }
    }
    if let Some(s) = project.sources.iter().find(|s| {
        s.kind == SourceKind::Postgres
            && s.connection_id.as_deref() == Some(connection_id)
            && s.schema.as_deref() == Some(rel.schema.as_str())
            && s.table_name.as_deref() == Some(rel.name.as_str())
    }) {
        return s.id.clone();
    }
    let id = fresh_id("src", &format!("{}_{}", rel.schema, rel.name), taken);
    project.sources.push(SourceDef {
        id: id.clone(),
        name: format!("{}.{}", rel.schema, rel.name),
        kind: SourceKind::Postgres,
        path: None,
        path_kind: Default::default(),
        connection_id: Some(connection_id.to_string()),
        connection_string: None,
        schema: Some(rel.schema.clone()),
        table_name: Some(rel.name.clone()),
        hive_partitioning: false,
    });
    id
}

fn ensure_query(
    project: &mut Project,
    taken: &mut HashSet<String>,
    connection_id: &str,
    rel: &PlannedRelation,
    prior: Option<&ImportedRelation>,
) -> (String, bool) {
    if let Some(rec) = prior {
        if project.workspace.query(&rec.query_id).is_some() {
            return (rec.query_id.clone(), false);
        }
    }
    let id = fresh_id("q", &format!("{}_{}", rel.schema, rel.name), taken);
    project.workspace.queries.push(QueryDef {
        id: id.clone(),
        name: format!("{}.{}", rel.schema, rel.name),
        steps: vec![TransformationStep::LoadPostgres {
            connection_id: Some(connection_id.to_string()),
            connection_string: String::new(),
            schema: rel.schema.clone(),
            table_name: rel.name.clone(),
            source_alias: None,
        }],
        execution: Default::default(),
    });
    (id, true)
}

fn ensure_map(
    project: &mut Project,
    taken: &mut HashSet<String>,
    plan: &PgImportPlan,
    rel: &PlannedRelation,
    prior: Option<&ImportedRelation>,
    warnings: &mut Vec<String>,
    touched: &mut Vec<String>,
    created: &mut Vec<String>,
) -> (Option<String>, BindingStatus, Vec<String>, bool) {
    if !rel.present {
        return (
            prior.and_then(|p| p.keymap_id.clone()),
            BindingStatus::Broken,
            vec!["relation is unavailable".into()],
            false,
        );
    }
    if !wants_map(rel) {
        let id = prior.and_then(|p| p.keymap_id.clone());
        if let Some(id) = &id {
            if map_is_referenced(project, id) {
                warnings.push(format!(
                    "kept KeyMap '{id}' because a query still applies it"
                ));
                touched.push(id.clone());
                return (Some(id.clone()), BindingStatus::QueryOnly, vec![], false);
            }
            project.workspace.key_maps.retain(|m| &m.id != id);
        }
        return (None, BindingStatus::QueryOnly, vec![], false);
    }
    let Some(binding) = rel.confirmed.as_ref() else {
        return (
            None,
            BindingStatus::QueryOnly,
            vec!["binding was not confirmed".into()],
            false,
        );
    };
    let issues = column_issues(rel, binding);
    if !issues.is_empty() {
        let existing = prior.and_then(|p| p.keymap_id.clone()).filter(|id| {
            project.workspace.key_map(id).is_some()
        });
        if let Some(id) = &existing {
            touched.push(id.clone());
            warnings.push(format!(
                "{}.{} binding is broken: {}",
                rel.schema,
                rel.name,
                issues.join("; ")
            ));
            return (Some(id.clone()), BindingStatus::Broken, issues, false);
        }
        warnings.push(format!(
            "{}.{} imported as a query — {}",
            rel.schema,
            rel.name,
            issues.join("; ")
        ));
        return (None, BindingStatus::Broken, issues, false);
    }
    let mut write_back = binding.write_back;
    if write_back {
        if let Some(reason) = write_back_refusal(rel, binding) {
            write_back = false;
            warnings.push(format!(
                "{}.{} write-back refused: {reason}",
                rel.schema, rel.name
            ));
        }
    }
    if rel.view_definition_available == Some(false) {
        warnings.push(format!(
            "{}.{} view definition is unavailable",
            rel.schema, rel.name
        ));
    }
    let canon = |names: &[String]| -> Vec<String> {
        names
            .iter()
            .filter_map(|n| resolve_catalog_name(&rel.columns, n).ok())
            .collect()
    };
    let from_columns = canon(&binding.from_columns);
    let output_columns = canon(&binding.output_columns);
    let editable_columns = canon(&binding.editable_columns);
    let prior_id = prior.and_then(|p| p.keymap_id.clone());
    if let Some(id) = &prior_id {
        if let Some(map) = project.workspace.key_maps.iter_mut().find(|m| &m.id == id) {
            if !matches!(map.storage, KeyMapStorage::Source { .. }) {
                warnings.push(format!(
                    "KeyMap '{id}' storage was not switched"
                ));
                touched.push(id.clone());
                return (
                    Some(id.clone()),
                    BindingStatus::Broken,
                    vec!["storage is not source; left unchanged".into()],
                    false,
                );
            }
            fill_source_map(
                map,
                &plan.connection_id,
                rel,
                &from_columns,
                &output_columns,
                &editable_columns,
                binding,
            );
            touched.push(id.clone());
            let status = if rel.quality_notes.is_empty() {
                BindingStatus::Confirmed
            } else {
                BindingStatus::Problem
            };
            return (Some(id.clone()), status, vec![], write_back);
        }
    }
    let id = fresh_id("km", &format!("{}_{}", rel.schema, rel.name), taken);
    let mut map = KeyMapDef::new(id.clone(), format!("{}.{}", rel.schema, rel.name));
    fill_source_map(
        &mut map,
        &plan.connection_id,
        rel,
        &from_columns,
        &output_columns,
        &editable_columns,
        binding,
    );
    if let Err(err) = map.validate() {
        warnings.push(format!("{}.{} map was not created: {err}", rel.schema, rel.name));
        return (None, BindingStatus::Broken, vec![err], false);
    }
    project.workspace.key_maps.push(map);
    created.push(id.clone());
    touched.push(id.clone());
    let status = if rel.quality_notes.is_empty() {
        BindingStatus::Confirmed
    } else {
        BindingStatus::Problem
    };
    (Some(id), status, vec![], write_back)
}

fn fill_source_map(
    map: &mut KeyMapDef,
    connection_id: &str,
    rel: &PlannedRelation,
    from_columns: &[String],
    output_columns: &[String],
    editable_columns: &[String],
    binding: &ConfirmedBinding,
) {
    map.entries.clear();
    map.storage = KeyMapStorage::Source {
        source: rel.schema.clone(),
        table: rel.name.clone(),
        connection_id: Some(connection_id.to_string()),
        db_schema: Some(rel.schema.clone()),
    };
    map.from_columns = from_columns.to_vec();
    map.from_column = from_columns.first().cloned().unwrap_or_default();
    map.output_columns = output_columns.to_vec();
    map.to_column = output_columns.first().cloned().unwrap_or_default();
    map.editable_columns = editable_columns.to_vec();
    match binding.time_mode {
        ImportTimeMode::Static => {
            map.time_mode = KeyMapTimeMode::None;
            map.valid_from_column = None;
            map.valid_to_column = None;
        }
        ImportTimeMode::RangeScd => {
            map.time_mode = KeyMapTimeMode::RangeScd;
            map.valid_from_column = binding
                .valid_from_column
                .as_ref()
                .and_then(|n| resolve_catalog_name(&rel.columns, n).ok());
            map.valid_to_column = binding
                .valid_to_column
                .as_ref()
                .and_then(|n| resolve_catalog_name(&rel.columns, n).ok());
        }
    }
}

fn map_is_referenced(project: &Project, map_id: &str) -> bool {
    project.workspace.queries.iter().any(|q| {
        q.steps.iter().any(|s| match s {
            TransformationStep::ApplyKeyMap { map_id: target, .. } => {
                target.compiler_id().ok() == Some(map_id)
            }
            _ => false,
        })
    })
}

fn build_working_query(
    project: &Project,
    taken: &mut HashSet<String>,
    _plan: &PgImportPlan,
    wq: &PlannedWorkingQuery,
    query_by_rel: &BTreeMap<(String, String), String>,
    map_by_rel: &BTreeMap<(String, String), String>,
) -> Option<QueryDef> {
    let left = resolve_built(
        project,
        wq.left_query_id.as_deref(),
        wq.left_relation.as_ref(),
        query_by_rel,
    )?;
    let map_id = map_by_rel.get(&wq.map_relation)?.clone();
    let map = project.workspace.key_map(&map_id)?;
    let mut steps = vec![
        TransformationStep::FromQuery {
            query_id: ObjectTarget::Local(left),
        },
        TransformationStep::ApplyKeyMap {
            column: wq.input_columns.first().cloned().unwrap_or_default(),
            columns: wq.input_columns.clone(),
            output_column: None,
            output_bindings: wq.output_bindings.clone(),
            as_of_column: if map.is_range_scd() {
                wq.as_of_column.clone()
            } else {
                None
            },
            map_id: ObjectTarget::Local(map_id),
            entries: vec![],
        },
    ];
    if wq.right_query_id.is_some() || wq.right_relation.is_some() {
        let right = resolve_built(
            project,
            wq.right_query_id.as_deref(),
            wq.right_relation.as_ref(),
            query_by_rel,
        )?;
        let mut left_on = wq.left_on.clone();
        let mut right_on = wq.right_on.clone();
        for eq in &wq.extra_equalities {
            left_on.push(eq.left.clone());
            right_on.push(eq.right.clone());
        }
        steps.push(TransformationStep::Join {
            right_query_id: ObjectTarget::Local(right),
            join_type: parse_join_type(wq.join_type.as_deref()).unwrap_or(JoinType::Left),
            left_on,
            right_on,
        });
    }
    let id = fresh_id("q", &wq.name, taken);
    Some(QueryDef {
        id,
        name: wq.name.clone(),
        steps,
        execution: Default::default(),
    })
}

fn resolve_built(
    project: &Project,
    query_id: Option<&str>,
    relation: Option<&(String, String)>,
    query_by_rel: &BTreeMap<(String, String), String>,
) -> Option<String> {
    if let Some((schema, name)) = relation {
        if let Some(id) = query_by_rel.get(&(schema.clone(), name.clone())) {
            return Some(id.clone());
        }
    }
    if let Some(id) = query_id {
        if project.workspace.query(id).is_some() {
            return Some(id.to_string());
        }
    }
    None
}

