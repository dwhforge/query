pub struct DbtProducer;

impl OutputProducer for DbtProducer {
    fn produce(
        &self,
        pipeline_name: &str,
        workspace: &Workspace,
        output_dir: &str,
        target: DbtTarget,
        dialect: WarehouseDialect,
    ) -> Result<String, String> {
        if matches!(target, DbtTarget::V2) {
            return Err(
                "dbt v2 export is reserved (ADR-0006) but not implemented yet. Use dbt_target: v1."
                    .into(),
            );
        }

        if dialect == WarehouseDialect::Postgres {
            if workspace_needs_s3_landing(&workspace.queries)
                || workspace.queries.iter().any(|q| {
                    q.steps.iter().any(|s| {
                        matches!(
                            s,
                            TransformationStep::LoadCsv { .. }
                                | TransformationStep::LoadParquet { .. }
                        )
                    })
                })
            {
                return Err(
                    "target_dialect=postgres: file/S3 sources need landing into Postgres before dbt export (ADR-0014). Use target_dialect=duckdb for live file reads, or land data first."
                        .into(),
                );
            }
            for q in &workspace.queries {
                validate_target_execution(q, dialect)?;
            }
        }

        let root = Path::new(output_dir).join(pipeline_name);
        let models = root.join("models");
        let staging = models.join("staging");
        let intermediate = models.join("intermediate");
        let marts = models.join("marts");
        create_dir_all(&staging).map_err(|e| e.to_string())?;
        create_dir_all(&intermediate).map_err(|e| e.to_string())?;
        create_dir_all(&marts).map_err(|e| e.to_string())?;

        let require = target.require_dbt_version();
        write_file(
            &root.join("dbt_project.yml"),
            &format!(
                "name: '{pipeline_name}'\n\
                 version: '1.0.0'\n\
                 config-version: 2\n\
                 require-dbt-version: [{require}]\n\
                 profile: '{pipeline_name}'\n\
                 model-paths: [\"models\"]\n\
                 models:\n\
                   {pipeline_name}:\n\
                     staging:\n\
                       +materialized: view\n\
                     intermediate:\n\
                       +materialized: view\n\
                     marts:\n\
                       +materialized: table\n\
                 # Generated by DWH-RS-QUERY for dbt {target}\n",
                target = target.as_str()
            ),
        )?;

        let profiles = match dialect {
            WarehouseDialect::Duckdb => format!(
                "{pipeline_name}:\n  target: dev\n  outputs:\n    dev:\n      type: duckdb\n      path: 'local.duckdb'\n      threads: 4\n"
            ),
            WarehouseDialect::Postgres => format!(
                "{pipeline_name}:\n  target: dev\n  outputs:\n    dev:\n      type: postgres\n      host: localhost\n      user: USER\n      password: PASS\n      port: 5432\n      dbname: DB\n      schema: analytics\n      threads: 4\n"
            ),
        };
        write_file(&root.join("profiles.yml.example"), &profiles)?;

        let order = topo_queries(workspace)?;
        let mut model_name_by_query: std::collections::HashMap<String, String> =
            std::collections::HashMap::new();
        let mut sources_yml = String::from("version: 2\nsources:\n");
        let mut has_pg = false;

        for qid in &order {
            let query = workspace
                .query(qid)
                .ok_or_else(|| format!("missing query {qid}"))?;
            let (folder, model_name) = {
                let name = dbt_model_name(workspace, query);
                let folder = if name.starts_with("mart_") {
                    &marts
                } else if name.starts_with("stg_") {
                    &staging
                } else {
                    &intermediate
                };
                (folder, name)
            };
            let sql = compile_query_as_dbt_model(query, &model_name_by_query, dialect)?;
            write_file(&folder.join(format!("{model_name}.sql")), &sql)?;
            model_name_by_query.insert(qid.clone(), model_name);

            if let Some(TransformationStep::LoadPostgres {
                schema,
                table_name,
                ..
            }) = query.steps.first()
            {
                if !has_pg {
                    sources_yml.push_str("  - name: postgres_raw\n    tables:\n");
                    has_pg = true;
                }
                let src_name = pg_dbt_source_name(schema, table_name);
                sources_yml.push_str(&format!(
                    "      - name: {src_name}\n        schema: {schema}\n        identifier: {table_name}\n"
                ));
            }
        }

        if has_pg {
            write_file(&models.join("sources.yml"), &sources_yml)?;
        } else {
            write_file(
                &models.join("sources.yml"),
                "version: 2\n# No postgres sources in this export.\nsources: []\n",
            )?;
        }

        Ok(root.to_string_lossy().into_owned())
    }
}

fn is_source_only_query(query: &crate::model::QueryDef) -> bool {
    matches!(
        query.steps.first(),
        Some(
            TransformationStep::LoadCsv { .. }
                | TransformationStep::LoadParquet { .. }
                | TransformationStep::LoadPostgres { .. }
        )
    ) && query.steps.len() == 1
}

/// dbt model file stem for a query (`stg_` / `int_` / `mart_`).
/// Layer prefixes are export-only — query names in the UI normally omit them.
/// If a user already put `stg_`/`int_`/`mart_` in the query name, keep as-is.
pub fn dbt_model_name(workspace: &Workspace, query: &crate::model::QueryDef) -> String {
    let stem = sanitize_id(&query.name);
    if stem.starts_with("stg_") || stem.starts_with("int_") || stem.starts_with("mart_") {
        return stem;
    }
    let prefix = if query.id == workspace.focus_query_id {
        "mart"
    } else if is_source_only_query(query) {
        "stg"
    } else {
        "int"
    };
    format!("{prefix}_{stem}")
}

/// Build query-id → model-name map in dependency order (for `ref()`).
pub fn dbt_model_names(workspace: &Workspace) -> Result<std::collections::HashMap<String, String>, String> {
    let order = topo_queries(workspace)?;
    let mut map = std::collections::HashMap::new();
    for qid in order {
        let query = workspace
            .query(&qid)
            .ok_or_else(|| format!("missing query {qid}"))?;
        map.insert(qid, dbt_model_name(workspace, query));
    }
    Ok(map)
}

/// Compiled dbt model SQL for one query (same body as export). Live Model tab.
pub fn preview_dbt_model_sql(
    workspace: &Workspace,
    query_id: &str,
    dialect: WarehouseDialect,
) -> Result<PreviewDbtModel, String> {
    let query = workspace
        .query(query_id)
        .ok_or_else(|| format!("query '{query_id}' not found"))?;
    let names = dbt_model_names(workspace)?;
    let sql = compile_query_as_dbt_model(query, &names, dialect)?;
    let model_name = names
        .get(query_id)
        .cloned()
        .unwrap_or_else(|| dbt_model_name(workspace, query));
    Ok(PreviewDbtModel {
        query_id: query_id.to_string(),
        model_name,
        sql,
    })
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct PreviewDbtModel {
    pub query_id: String,
    pub model_name: String,
    pub sql: String,
}

fn compile_query_as_dbt_model(
    query: &crate::model::QueryDef,
    models: &std::collections::HashMap<String, String>,
    dialect: WarehouseDialect,
) -> Result<String, String> {
    // v1: collapse query into one model SQL (WITH inside file) using ref() for deps.
    if query.steps.is_empty() {
        return Err(format!("query '{}' empty", query.id));
    }

    // Single Load* / FromQuery — one-shot select.
    if query.steps.len() == 1 {
        return Ok(match &query.steps[0] {
            TransformationStep::LoadCsv { path } => format!(
                "-- source: csv\nselect * from read_csv_auto('{}')\n",
                escape_sql_string(path)
            ),
            TransformationStep::LoadParquet { path, .. } => format!(
                "-- source: parquet\nselect * from read_parquet('{}')\n",
                escape_sql_string(path)
            ),
            TransformationStep::LoadPostgres {
                schema,
                table_name,
                ..
            } => {
                let src = pg_dbt_source_name(schema, table_name);
                format!("select * from {{{{ source('postgres_raw', '{src}') }}}}\n")
            }
            TransformationStep::FromQuery { query_id } => {
                let m = models.get(query_id).ok_or_else(|| {
                    format!("dbt FromQuery: missing model for '{query_id}'")
                })?;
                format!("select * from {{{{ ref('{m}') }}}}\n")
            }
            TransformationStep::SqlModel { raw_sql } => {
                let mut sql = raw_sql.trim().trim_end_matches(';').to_string();
                for dep in direct_deps(std::slice::from_ref(&query.steps[0])) {
                    if let Some(m) = models.get(&dep) {
                        sql = sql.replace(
                            &format!("{{{{query:{dep}}}}}"),
                            &format!("{{{{ ref('{m}') }}}}"),
                        );
                    }
                }
                if !sql.ends_with('\n') {
                    sql.push('\n');
                }
                sql
            }
            _ => {
                return Err(
                    "single-step query must be Load*, FromQuery, or SqlModel".into(),
                )
            }
        });
    }

    let mut ctes = Vec::new();
    for (idx, step) in query.steps.iter().enumerate() {
        let name = format!("s{idx}");
        let prev = if idx > 0 {
            format!("s{}", idx - 1)
        } else {
            String::new()
        };
        let body = match step {
            TransformationStep::LoadCsv { path } => format!(
                "select * from read_csv_auto('{}')",
                escape_sql_string(path)
            ),
            TransformationStep::LoadParquet { path, .. } => format!(
                "select * from read_parquet('{}')",
                escape_sql_string(path)
            ),
            TransformationStep::LoadPostgres {
                schema,
                table_name,
                ..
            } => {
                let src = pg_dbt_source_name(schema, table_name);
                format!("select * from {{{{ source('postgres_raw', '{src}') }}}}")
            }
            TransformationStep::FromQuery { query_id } => {
                if !prev.is_empty() {
                    return Err("dbt FromQuery must be the first step".into());
                }
                let m = models.get(query_id).ok_or_else(|| {
                    format!("dbt FromQuery: missing model for '{query_id}'")
                })?;
                format!("select * from {{{{ ref('{m}') }}}}")
            }
            TransformationStep::SqlModel { raw_sql } => {
                if !prev.is_empty() {
                    return Err("dbt SqlModel must be the first step".into());
                }
                let mut sql = raw_sql.trim().trim_end_matches(';').to_string();
                for dep in direct_deps(std::slice::from_ref(step)) {
                    if let Some(m) = models.get(&dep) {
                        sql = sql.replace(
                            &format!("{{{{query:{dep}}}}}"),
                            &format!("{{{{ ref('{m}') }}}}"),
                        );
                    }
                }
                sql
            }
            TransformationStep::Filter { condition } => {
                format!("select * from {prev} where {condition}")
            }
            TransformationStep::SelectColumns { columns } => {
                let cols = columns
                    .iter()
                    .map(|c| quote_ident(c))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("select {cols} from {prev}")
            }
            TransformationStep::RenameColumn { from, to } => {
                sql_rename_column(dialect, &prev, from, to)?
            }
            TransformationStep::DeriveColumn { name, expression } => format!(
                "select *, ({expression}) as {} from {prev}",
                quote_ident(name)
            ),
            TransformationStep::GroupBy {
                dimensions,
                aggregates,
            } => {
                let dims = dimensions
                    .iter()
                    .map(|c| quote_ident(c))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!(
                    "select {dims}, {} from {prev} group by {dims}",
                    aggregates.join(", ")
                )
            }
            TransformationStep::SortBy {
                column,
                descending,
            } => {
                let order = if *descending { "desc" } else { "asc" };
                format!(
                    "select * from {prev} order by {} {order}",
                    quote_ident(column)
                )
            }
            TransformationStep::Limit { n } => {
                if *n == 0 {
                    return Err("dbt Limit: n must be >= 1".into());
                }
                format!("select * from {prev} limit {n}")
            }
            TransformationStep::Join {
                right_query_id,
                join_type,
                left_on,
                right_on,
            } => {
                let right_model = models.get(right_query_id).ok_or_else(|| {
                    format!("dbt Join: missing model for '{right_query_id}'")
                })?;
                let right_ref = format!("{{{{ ref('{right_model}') }}}}");
                let join_kw = match join_type {
                    JoinType::Inner => "inner join",
                    JoinType::Left => "left join",
                    JoinType::Right => "right join",
                    JoinType::Full => "full outer join",
                };
                if left_on == right_on {
                    let using = left_on
                        .iter()
                        .map(|c| quote_ident(c))
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!(
                        "select * from {prev} as l {join_kw} {right_ref} as r using ({using})"
                    )
                } else {
                    let ons: Vec<String> = left_on
                        .iter()
                        .zip(right_on.iter())
                        .map(|(l, r)| {
                            format!("l.{} = r.{}", quote_ident(l), quote_ident(r))
                        })
                        .collect();
                    format!(
                        "select * from {prev} as l {join_kw} {right_ref} as r on {}",
                        ons.join(" and ")
                    )
                }
            }
            TransformationStep::Append { other_query_ids } => {
                let mut acc = format!("select * from {prev}");
                for oid in other_query_ids {
                    let m = models
                        .get(oid)
                        .ok_or_else(|| format!("dbt Append: missing '{oid}'"))?;
                    let right = format!("{{{{ ref('{m}') }}}}");
                    acc = match dialect {
                        WarehouseDialect::Duckdb => {
                            format!("{acc} union all by name select * from {right}")
                        }
                        WarehouseDialect::Postgres => {
                            format!("{acc} union all select * from {right}")
                        }
                    };
                }
                acc
            }
            TransformationStep::CustomSql { raw_sql } => {
                let mut sql = raw_sql.replace("{{prev_step}}", &prev);
                for dep in direct_deps(std::slice::from_ref(step)) {
                    if let Some(m) = models.get(&dep) {
                        sql = sql.replace(
                            &format!("{{{{query:{dep}}}}}"),
                            &format!("{{{{ ref('{m}') }}}}"),
                        );
                    }
                }
                sql
            }
        };
        ctes.push(format!("  {name} as (\n    {body}\n  )"));
    }

    let last = format!("s{}", query.steps.len() - 1);
    Ok(format!(
        "with\n{}\nselect * from {last}\n",
        ctes.join(",\n")
    ))
}

/// Unique dbt `source()` table name: `{schema}__{table}` (stable across schemas).
fn pg_dbt_source_name(schema: &str, table: &str) -> String {
    format!(
        "{}__{}",
        sanitize_id(schema),
        sanitize_id(table)
    )
}

fn write_file(path: &PathBuf, content: &str) -> Result<(), String> {
    let mut f = File::create(path).map_err(|e| e.to_string())?;
    f.write_all(content.as_bytes()).map_err(|e| e.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{JoinType, QueryDef, TransformationStep};
    use std::env::temp_dir;

    #[test]
    fn exports_join_workspace() {
        let dir = temp_dir().join(format!("dwh_dbt_test_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        create_dir_all(&dir).unwrap();

        let ws = Workspace {
            queries: vec![
                QueryDef {
                    id: "dim".into(),
                    name: "dim_region".into(),
                    steps: vec![TransformationStep::LoadCsv {
                        path: "dim.csv".into(),
                    }],
                 execution: Default::default(),
},
                QueryDef {
                    id: "fact".into(),
                    name: "fact_sales".into(),
                    steps: vec![
                        TransformationStep::LoadCsv {
                            path: "fact.csv".into(),
                        },
                        TransformationStep::Join {
                            right_query_id: "dim".into(),
                            join_type: JoinType::Inner,
                            left_on: vec!["region".into()],
                            right_on: vec!["region".into()],
                        },
                    ],
                 execution: Default::default(),
},
            ],
            focus_query_id: "fact".into(),
        };

        let path = DbtProducer
            .produce(
                "demo",
                &ws,
                dir.to_str().unwrap(),
                DbtTarget::V1,
                WarehouseDialect::Duckdb,
            )
            .unwrap();
        assert!(Path::new(&path).join("dbt_project.yml").exists());
        let project = std::fs::read_to_string(Path::new(&path).join("dbt_project.yml")).unwrap();
        assert!(project.contains("require-dbt-version"));
        assert!(project.contains(">=1.7.0,<2.0.0"));
        assert!(Path::new(&path)
            .join("models/staging/stg_dim_region.sql")
            .exists());
        assert!(Path::new(&path)
            .join("models/marts/mart_fact_sales.sql")
            .exists());
        let mart = std::fs::read_to_string(
            Path::new(&path).join("models/marts/mart_fact_sales.sql"),
        )
        .unwrap();
        assert!(mart.contains("ref('stg_dim_region')"));

        let v2 = DbtProducer.produce(
            "demo_v2",
            &ws,
            dir.to_str().unwrap(),
            DbtTarget::V2,
            WarehouseDialect::Duckdb,
        );
        assert!(v2.is_err());
    }

    #[test]
    fn explicit_layer_prefix_not_doubled() {
        let ws = Workspace {
            queries: vec![QueryDef {
                id: "q".into(),
                name: "stg_sales".into(),
                steps: vec![TransformationStep::LoadCsv {
                    path: "x.csv".into(),
                }],
             execution: Default::default(),
}],
            focus_query_id: "q".into(),
        };
        let q = ws.query("q").unwrap();
        assert_eq!(dbt_model_name(&ws, q), "stg_sales");
    }
}
