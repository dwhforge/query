import { useEffect, useMemo, useState } from "react";
import type { ConnectionDef, KeyMapDef, KeyMapStorage } from "../types/pipeline";
import {
  describePostgresObject,
  listPostgresObjects,
  type PostgresColumn,
  type PostgresObject,
} from "../lib/bridge";

export type KeyMapBindResult = {
  storage: Extract<KeyMapStorage, { kind: "source" }>;
  from_column: string;
  /** Composite From columns (ADR-0024); length ≥ 1. */
  from_columns: string[];
  to_column: string;
  editable_columns: string[];
};

export type KeyMapBindWizardProps = {
  postgresConnections: ConnectionDef[];
  /** Prefill when rebinding an existing map. */
  initial?: Partial<KeyMapBindResult> & { name?: string };
  onCancel: () => void;
  onConfirm: (result: KeyMapBindResult) => void;
};

function pickDefaultFromTo(cols: PostgresColumn[]): {
  from: string;
  to: string;
} {
  const names = cols.map((c) => c.name);
  const lower = new Map(names.map((n) => [n.toLowerCase(), n]));
  const from =
    lower.get("from") ??
    lower.get("alias") ??
    lower.get("src") ??
    lower.get("source_key") ??
    names[0] ??
    "from";
  const toCand =
    lower.get("to") ??
    lower.get("id") ??
    lower.get("canon") ??
    lower.get("target_key") ??
    names.find((n) => n !== from) ??
    "to";
  return { from, to: toCand };
}

/** ADR-0022 bind wizard: connection → table → From/To → editable attrs. */
export function KeyMapBindWizard({
  postgresConnections,
  initial,
  onCancel,
  onConfirm,
}: KeyMapBindWizardProps) {
  const [connectionId, setConnectionId] = useState(
    initial?.storage?.connection_id ?? "",
  );
  const [objects, setObjects] = useState<PostgresObject[]>([]);
  const [catalogStatus, setCatalogStatus] = useState<string | null>(null);
  const [schema, setSchema] = useState(initial?.storage?.source ?? "");
  const [table, setTable] = useState(initial?.storage?.table ?? "");
  const [columns, setColumns] = useState<PostgresColumn[]>([]);
  const [colStatus, setColStatus] = useState<string | null>(null);
  const [fromCols, setFromCols] = useState<string[]>(() => {
    if (initial?.from_columns?.length) return [...initial.from_columns];
    if (initial?.from_column?.trim()) return [initial.from_column];
    return [];
  });
  const [toCol, setToCol] = useState(initial?.to_column ?? "");
  const [editable, setEditable] = useState<Set<string>>(
    () => new Set(initial?.editable_columns ?? []),
  );
  const [error, setError] = useState<string | null>(null);

  const dsn = useMemo(() => {
    const c = postgresConnections.find((x) => x.id === connectionId);
    return c?.postgres?.connection_string?.trim() ?? "";
  }, [postgresConnections, connectionId]);

  useEffect(() => {
    if (!dsn) {
      setObjects([]);
      setCatalogStatus(
        postgresConnections.length === 0
          ? "No Postgres connection"
          : connectionId
            ? "Connection has no DSN"
            : null,
      );
      return;
    }
    let cancelled = false;
    setCatalogStatus("Loading schemas…");
    void listPostgresObjects(dsn)
      .then((list) => {
        if (cancelled) return;
        setObjects(list);
        setCatalogStatus(list.length === 0 ? "No tables/views" : null);
      })
      .catch((e) => {
        if (cancelled) return;
        setObjects([]);
        setCatalogStatus(typeof e === "string" ? e : String(e));
      });
    return () => {
      cancelled = true;
    };
  }, [dsn, connectionId, postgresConnections.length]);

  const schemas = useMemo(() => {
    const s = new Set(objects.map((o) => o.schema));
    return [...s].sort((a, b) => a.localeCompare(b));
  }, [objects]);

  const tablesInSchema = useMemo(() => {
    if (!schema) return [];
    return objects
      .filter((o) => o.schema === schema)
      .map((o) => o.name)
      .sort((a, b) => a.localeCompare(b));
  }, [objects, schema]);

  useEffect(() => {
    if (!dsn || !schema.trim() || !table.trim()) {
      setColumns([]);
      setColStatus(null);
      return;
    }
    let cancelled = false;
    setColStatus("Describing columns…");
    void describePostgresObject(dsn, schema, table)
      .then((cols) => {
        if (cancelled) return;
        setColumns(cols);
        setColStatus(null);
        const { from, to } = pickDefaultFromTo(cols);
        const nextFroms =
          fromCols.length && fromCols.every((c) => c.trim())
            ? fromCols
            : [from];
        const nextTo = toCol.trim() || to;
        setFromCols(nextFroms);
        setToCol(nextTo);
        // Default editable: non-autogenerated except From/To (ADR-0022).
        if (editable.size === 0 && !(initial?.editable_columns?.length)) {
          const fromSet = new Set(nextFroms);
          const def = new Set(
            cols
              .filter(
                (c) =>
                  !c.is_autogenerated &&
                  !fromSet.has(c.name) &&
                  c.name !== nextTo,
              )
              .map((c) => c.name),
          );
          setEditable(def);
        }
      })
      .catch((e) => {
        if (cancelled) return;
        setColumns([]);
        setColStatus(typeof e === "string" ? e : String(e));
      });
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps -- describe when table binding changes
  }, [dsn, schema, table]);

  const fieldClass =
    "mt-1 w-full rounded-md border border-slate-700 bg-slate-950 px-2 py-1.5 text-[12px] text-slate-100";
  const labelClass = "block text-[11px] font-medium text-slate-400";

  function toggleEditable(name: string) {
    setEditable((prev) => {
      const next = new Set(prev);
      if (next.has(name)) next.delete(name);
      else next.add(name);
      return next;
    });
  }

  function confirm() {
    setError(null);
    if (!connectionId) {
      setError("Select a Postgres connection");
      return;
    }
    if (!schema.trim() || !table.trim()) {
      setError("Select schema and table");
      return;
    }
    const cleanedFrom = fromCols.map((c) => c.trim()).filter(Boolean);
    if (!cleanedFrom.length || !toCol.trim()) {
      setError("From and To columns are required");
      return;
    }
    if (cleanedFrom.includes(toCol.trim())) {
      setError("From and To must differ");
      return;
    }
    if (new Set(cleanedFrom).size !== cleanedFrom.length) {
      setError("From columns must be unique");
      return;
    }
    const fromSet = new Set(cleanedFrom);
    onConfirm({
      storage: {
        kind: "source",
        source: schema.trim(),
        table: table.trim(),
        connection_id: connectionId,
      },
      from_column: cleanedFrom[0]!,
      from_columns: cleanedFrom,
      to_column: toCol.trim(),
      editable_columns: [...editable].filter(
        (c) => !fromSet.has(c) && c !== toCol.trim(),
      ),
    });
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
      <div className="flex max-h-[90vh] w-full max-w-lg flex-col overflow-hidden rounded-xl border border-teal-900/50 bg-[#071018] shadow-2xl">
        <div className="border-b border-slate-800 px-4 py-3">
          <h2 className="text-base font-semibold text-slate-100">
            Bind KeyMap to Postgres
          </h2>
          <p className="mt-0.5 text-[11px] text-slate-500">
            Connection → table → From/To → editable columns (ADR-0022)
          </p>
        </div>
        <div className="min-h-0 flex-1 space-y-3 overflow-y-auto px-4 py-3">
          <label className={labelClass}>
            Connection
            <select
              value={connectionId}
              onChange={(e) => {
                setConnectionId(e.target.value);
                setSchema("");
                setTable("");
                setColumns([]);
              }}
              className={fieldClass}
            >
              <option value="">Select…</option>
              {postgresConnections.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.name || c.id}
                </option>
              ))}
            </select>
          </label>
          {catalogStatus && (
            <p className="text-[11px] text-slate-500">{catalogStatus}</p>
          )}
          <div className="grid grid-cols-2 gap-2">
            <label className={labelClass}>
              Schema
              <select
                value={schema}
                disabled={!dsn}
                onChange={(e) => {
                  setSchema(e.target.value);
                  setTable("");
                  setColumns([]);
                }}
                className={`${fieldClass} font-mono disabled:opacity-40`}
              >
                <option value="">Pick…</option>
                {schemas.map((s) => (
                  <option key={s} value={s}>
                    {s}
                  </option>
                ))}
              </select>
            </label>
            <label className={labelClass}>
              Table
              <select
                value={table}
                disabled={!schema}
                onChange={(e) => setTable(e.target.value)}
                className={`${fieldClass} font-mono disabled:opacity-40`}
              >
                <option value="">Pick…</option>
                {tablesInSchema.map((t) => (
                  <option key={t} value={t}>
                    {t}
                  </option>
                ))}
              </select>
            </label>
          </div>
          {colStatus && (
            <p className="text-[11px] text-slate-500">{colStatus}</p>
          )}
          {columns.length > 0 && (
            <>
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <span className={labelClass}>From columns (tuple)</span>
                  <button
                    type="button"
                    onClick={() => {
                      const used = new Set(fromCols);
                      const next =
                        columns.find((c) => !used.has(c.name) && c.name !== toCol)
                          ?.name ?? "";
                      if (next) setFromCols([...fromCols, next]);
                    }}
                    className="rounded border border-slate-700 px-1.5 py-0.5 text-[10px] text-slate-400 hover:text-teal-200"
                  >
                    + From
                  </button>
                </div>
                {fromCols.map((fc, i) => (
                  <div key={`from-${i}`} className="flex gap-1">
                    <select
                      value={fc}
                      onChange={(e) => {
                        const next = [...fromCols];
                        next[i] = e.target.value;
                        setFromCols(next);
                      }}
                      className={`${fieldClass} mt-0 font-mono`}
                    >
                      {columns.map((c) => (
                        <option key={c.name} value={c.name}>
                          {c.name}
                          {c.is_autogenerated ? " (auto)" : ""}
                        </option>
                      ))}
                    </select>
                    {fromCols.length > 1 && (
                      <button
                        type="button"
                        onClick={() =>
                          setFromCols(fromCols.filter((_, j) => j !== i))
                        }
                        className="rounded border border-slate-700 px-2 text-slate-500 hover:text-rose-300"
                      >
                        ×
                      </button>
                    )}
                  </div>
                ))}
                <label className={labelClass}>
                  To column
                  <select
                    value={toCol}
                    onChange={(e) => setToCol(e.target.value)}
                    className={`${fieldClass} font-mono`}
                  >
                    {columns.map((c) => (
                      <option key={c.name} value={c.name}>
                        {c.name}
                        {c.is_autogenerated ? " (auto)" : ""}
                      </option>
                    ))}
                  </select>
                </label>
              </div>
              <fieldset>
                <legend className={labelClass}>
                  Editable attributes
                  <span className="ml-1 font-normal text-slate-600">
                    (serial/identity off by default)
                  </span>
                </legend>
                <div className="mt-1 max-h-40 space-y-1 overflow-y-auto rounded-md border border-slate-800 p-2">
                  {columns
                    .filter(
                      (c) => !fromCols.includes(c.name) && c.name !== toCol,
                    )
                    .map((c) => (
                      <label
                        key={c.name}
                        className="flex items-center gap-2 text-[12px] text-slate-300"
                      >
                        <input
                          type="checkbox"
                          checked={editable.has(c.name)}
                          onChange={() => toggleEditable(c.name)}
                        />
                        <span className="font-mono">{c.name}</span>
                        <span className="text-[10px] text-slate-600">
                          {c.data_type}
                          {c.is_autogenerated ? " · auto" : ""}
                        </span>
                      </label>
                    ))}
                  {columns.filter(
                    (c) => !fromCols.includes(c.name) && c.name !== toCol,
                  ).length === 0 && (
                    <p className="text-[11px] text-slate-600">
                      No extra columns — From/To only
                    </p>
                  )}
                </div>
              </fieldset>
            </>
          )}
          {error && (
            <p className="text-[12px] text-amber-200">{error}</p>
          )}
        </div>
        <div className="flex justify-end gap-2 border-t border-slate-800 px-4 py-3">
          <button
            type="button"
            onClick={onCancel}
            className="rounded-lg border border-slate-700 px-3 py-2 text-sm text-slate-300 hover:border-slate-500"
          >
            Cancel
          </button>
          <button
            type="button"
            onClick={confirm}
            className="rounded-lg bg-teal-500 px-4 py-2 text-sm font-semibold text-slate-950 hover:bg-teal-400"
          >
            Bind
          </button>
        </div>
      </div>
    </div>
  );
}

/** Apply bind result onto a KeyMapDef (clears local entries — WH is SoT). */
export function applyKeyMapBind(
  map: KeyMapDef,
  bind: KeyMapBindResult,
): KeyMapDef {
  return {
    ...map,
    storage: bind.storage,
    from_column: bind.from_column,
    from_columns: bind.from_columns?.length
      ? bind.from_columns
      : [bind.from_column],
    to_column: bind.to_column,
    editable_columns: bind.editable_columns,
    entries: [],
  };
}
