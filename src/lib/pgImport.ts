export function relKey(schema: string, name: string): string {
  return `${schema}.${name}`;
}

/** Display hint only. The host scan's `rule_match` is the prefix authority. */
export function literalPrefixMatch(name: string, prefixes: string[]): boolean {
  return prefixes.some((p) => p.length > 0 && name.startsWith(p));
}

export function writeBackBlock(
  kind: string,
  insertOk: boolean,
  updateOk: boolean,
  deleteOk: boolean,
  uniqueSets: string[][],
  binding: ConfirmedBinding,
): string | null {
  if (kind !== "table" && kind !== "partitioned_table") {
    return "Запись доступна только для таблиц";
  }
  if (!(insertOk && updateOk && deleteOk)) {
    return "Нужны права INSERT, UPDATE и DELETE";
  }
  const key = binding.from_columns.map((c) => c.toLowerCase());
  if (binding.time_mode === "range_scd" && binding.valid_from_column) {
    key.push(binding.valid_from_column.toLowerCase());
  }
  const ok = uniqueSets.some((set) => {
    const got = set.map((c) => c.toLowerCase()).sort().join("\0");
    return got === [...key].sort().join("\0");
  });
  if (!ok) return "Нет уникального ограничения на идентичность строки";
  return null;
}
